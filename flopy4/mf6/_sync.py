"""Sync the generated ``flopy4.mf6`` classes to an MF6 version."""

import ast
import os
import shutil
import tempfile
import warnings
from collections.abc import Iterable
from dataclasses import dataclass
from os import PathLike
from pathlib import Path

_MF6_ROOT = Path(__file__).parent
_DFN_SCHEMA_VERSION = "2.0.0.dev3"
_DEFAULT_REPO = "MODFLOW-ORG/modflow6"
_CONTRACT = "_contract.py"
_GENERATED_HEADER = "# autogenerated file, do not modify"


class SyncError(Exception):
    """A sync couldn't write the generated classes."""


@dataclass(frozen=True)
class SyncResult:
    """The outcome of a :func:`sync`.

    Attributes
    ----------
    version :
        The MF6 version recorded in ``_contract.py``, or ``"unknown"``.
    source :
        Where the DFNs came from: an ``owner/repo@ref`` release ID or a
        local directory.
    outdir :
        The directory the classes and contract were written to.
    files :
        The generated module files.
    kept :
        Generated modules from an earlier sync that this source has no
        DFN for. They're left in place, since other modules may import
        them, and stay in the contract's file list.
    removed :
        Generated modules that neither this sync nor the previous
        contract lists, e.g. ones an earlier sync created before
        ``pip install --upgrade`` restored the release's contract.
    """

    version: str
    source: str
    outdir: Path
    files: tuple[Path, ...]
    kept: tuple[Path, ...] = ()
    removed: tuple[Path, ...] = ()


def _resolve_release_id(release_id: str | None, verbose: bool = False) -> str:
    """Resolve a release_id, falling back to the discovered binary's version
    or the latest release if no release_id is given.
    """
    if release_id is not None:
        if "@" not in release_id:
            return f"{_DEFAULT_REPO}@{release_id}"
        return release_id

    # Try to read the version from a binary on PATH.
    from flopy4.mf6._compat import _query_mf6_version

    for name in ("mf6", "mf6.exe"):
        exe = shutil.which(name)
        if exe:
            version = _query_mf6_version(exe)
            if version:
                if verbose:
                    print(f"Detected MF6 {version} at {exe}")
                return f"{_DEFAULT_REPO}@{version}"

    # Fall back to @latest.
    if verbose:
        print("No MF6 binary found on PATH; resolving to latest release.")
    return f"{_DEFAULT_REPO}@latest"


def _local_mf6_version(path: Path) -> str:
    """The MF6 version of DFNs read from a local directory: the version.txt
    of the modflow6 checkout the DFNs are in (they live at
    doc/mf6io/mf6ivar/dfn), else "unknown".
    """
    if "modflow6" in path.parts and len(path.parents) > 3:
        version_file = path.parents[3] / "version.txt"
        if version_file.is_file():
            return version_file.read_text().strip()
    return "unknown"


def _populate_remote_cache(registry, release_id: str, force: bool = False) -> None:
    """Populate the registry's DFN cache.

    Tries ``registry.sync()`` first (requires a ``dfns.zip`` release asset).
    Falls back to fetching DFNs from the repository tree when that asset is
    not yet available — writes directly into the registry's cache path so
    ``registry.spec()`` finds the files in the expected location.

    Parameters
    ----------
    force :
        Re-fetch even if the cache already exists. Should be True for
        branch refs (mutable) and False for pinned release tags.
    """
    if not force and registry.cache_path.exists() and any(registry.cache_path.iterdir()):
        return
    try:
        registry.sync()
    except Exception:
        # dfns.zip not yet a release asset; fetch from the git tree instead.
        from modflow_devtools.dfns import fetch_dfns

        owner_repo, tag = release_id.split("@", 1)
        owner, repo = owner_repo.split("/")
        registry.cache_path.mkdir(parents=True, exist_ok=True)
        fetch_dfns(owner=owner, repo=repo, ref=tag, outdir=registry.cache_path)


def _contract_text(mf6_version: str, files: Iterable[str]) -> str:
    lines = "".join(f'    "{f}",\n' for f in sorted(files))
    return (
        f"{_GENERATED_HEADER}\n"
        f'MF6_VERSION = "{mf6_version}"\n'
        f'DFN_SCHEMA_VERSION = "{_DFN_SCHEMA_VERSION}"\n'
        f"GENERATED_FILES = (\n{lines})\n"
    )


def _contract_files(outdir: Path) -> set[str] | None:
    """The ``GENERATED_FILES`` recorded in ``outdir``'s contract, read
    without importing it. None if there's no contract or no file list
    (contracts written before sync tracked files)."""
    try:
        tree = ast.parse((outdir / _CONTRACT).read_text())
    except (OSError, SyntaxError):
        return None
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "GENERATED_FILES"
        ):
            return set(ast.literal_eval(node.value))
    return None


def _generated_files(outdir: Path) -> set[str]:
    """Paths, relative to ``outdir``, of the generated modules on disk."""
    found = set()
    for path in outdir.rglob("*.py"):
        rel = path.relative_to(outdir)
        if rel.as_posix() == _CONTRACT or any(p.startswith(".") for p in rel.parts):
            continue
        with path.open() as f:
            if f.readline().rstrip("\n") == _GENERATED_HEADER:
                found.add(rel.as_posix())
    return found


def find_orphans(outdir: str | PathLike | None = None) -> list[Path]:
    """Generated modules in ``outdir`` that its contract doesn't list.

    These are modules an earlier sync created that the installed release
    doesn't ship, e.g. after ``pip install --upgrade`` restored the
    release's contract. Empty if the contract has no file list.
    """
    outdir = Path(outdir) if outdir is not None else _MF6_ROOT
    listed = _contract_files(outdir)
    if listed is None:
        return []
    return [outdir / f for f in sorted(_generated_files(outdir) - listed)]


def _check_writable(path: Path) -> None:
    """Raise SyncError unless ``path``, or its nearest existing ancestor
    if it doesn't exist yet, is writable."""
    while not path.exists():
        path = path.parent
    if not os.access(path, os.W_OK):
        raise SyncError(
            f"flopy4 is installed to a read-only location ({path}). "
            "Install into a virtual environment and try again, or use "
            "`pip install --user flopy4` for a user-writable install."
        )


def _swap(stage: Path, outdir: Path, replace: Iterable[str], remove: Iterable[str]) -> None:
    """Move the staged files over their counterparts in ``outdir`` and
    remove ``remove``, all or nothing: on failure, restore what was
    moved. Displaced files go to a backup in ``stage``."""
    replace, remove = list(replace), list(remove)
    replacing = set(replace)
    for rel in replace + remove:
        _check_writable((outdir / rel).parent)
    backup = stage / ".backup"
    done: list[str] = []
    try:
        for rel in replace + remove:
            dst = outdir / rel
            if dst.exists():
                (backup / rel).parent.mkdir(parents=True, exist_ok=True)
                os.replace(dst, backup / rel)
            done.append(rel)
            if rel in replacing:
                dst.parent.mkdir(parents=True, exist_ok=True)
                os.replace(stage / rel, dst)
    except BaseException:
        for rel in reversed(done):
            dst, bak = outdir / rel, backup / rel
            if bak.exists():
                os.replace(bak, dst)
            elif dst.exists():
                dst.unlink()
        raise


def sync(
    source: str | PathLike | None = None,
    *,
    exe: str | PathLike | None = None,
    mf6_version: str | None = None,
    all_packages: bool = False,
    force: bool = False,
    outdir: str | PathLike | None = None,
    verbose: bool = False,
) -> SyncResult:
    """Regenerate the ``flopy4.mf6`` classes for an MF6 version.

    Fetches or reads the DFNs, regenerates the component classes, and
    records the MF6 version in ``_contract.py``. Does not install an MF6
    binary.

    Parameters
    ----------
    source :
        Where to get the DFNs: a release ID (``owner/repo@ref``), a bare
        ref (``6.6.0``, ``develop``; the repo defaults to
        ``MODFLOW-ORG/modflow6``), or a local DFN directory. If omitted,
        uses the version of the ``mf6`` binary on PATH, else the latest
        release.
    exe :
        An MF6 executable to read the DFNs from (``mf6 --spec``). Not
        supported yet. Mutually exclusive with ``source``.
    mf6_version :
        The MF6 version to record, overriding the one inferred from the
        source.
    all_packages :
        Generate every component, including ones with no module yet. By
        default only existing modules are regenerated.
    force :
        Re-fetch remote DFNs even if they are cached. Branch refs are
        always re-fetched.
    outdir :
        Where to write the classes and contract. Defaults to the installed
        ``flopy4.mf6`` package.
    verbose :
        Print progress.

    Returns
    -------
    SyncResult
    """
    if exe is not None:
        if source is not None:
            raise ValueError("Pass either source or exe, not both.")
        raise NotImplementedError(
            "Syncing from an MF6 executable needs `mf6 --spec`, which MF6 doesn't support yet."
        )

    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message=".*modflow_devtools.dfns.*experimental.*")
        from modflow_devtools.dfns import LocalDfnRegistry, RemoteDfnRegistry

    from flopy4.mf6.utils.codegen.make import make_modules

    outdir = Path(outdir).expanduser().resolve() if outdir is not None else _MF6_ROOT
    _check_writable(outdir)

    path = Path(source).expanduser() if source is not None else None
    if path is not None and not path.is_dir():
        # A path-like source without a ref (a Path, or a string with a
        # separator but no "@") is a local directory that doesn't exist,
        # not a release ID.
        if isinstance(source, PathLike) or ("/" in str(source) and "@" not in str(source)):
            raise FileNotFoundError(f"DFN directory not found: {path}")
    if path is not None and path.is_dir():
        if verbose:
            print(f"Generating flopy4.mf6 from local DFNs: {path}")
        registry = LocalDfnRegistry(path=path)
        source = str(path)
        version = mf6_version or _local_mf6_version(path)
    else:
        release_id = _resolve_release_id(
            str(source) if source is not None else None, verbose=verbose
        )
        if verbose:
            print(f"Generating flopy4.mf6 from remote release: {release_id}")
        if "/" not in release_id.split("@")[0]:
            raise ValueError(
                f"source must be 'owner/repo@ref', a ref, or a local directory; got: {release_id!r}"
            )
        registry = RemoteDfnRegistry(release_id=release_id)
        source = release_id
        version = mf6_version or registry.latest_tag() or "unknown"
        # Branch refs are mutable: always re-fetch unless the version is a
        # pinned semver tag (first char is a digit).
        is_branch = not version[0].isdigit()
        _populate_remote_cache(registry, release_id, force=force or is_branch)

    if version == "unknown":
        warnings.warn(
            f"MF6 version is unknown for DFNs from '{source}'. "
            "Pass mf6_version to record it explicitly in _contract.py.",
            stacklevel=2,
        )

    from flopy4.mf6.utils.codegen.dfn2py import _SKIP, check_mixins

    dfns = registry.spec(schema_version=_DFN_SCHEMA_VERSION).components
    check_mixins(dfns)
    outdir.mkdir(parents=True, exist_ok=True)

    # Generate into a staging directory inside outdir, so ruff formats with
    # the project's config and the swap is a rename on the same filesystem.
    # Nothing in outdir changes until every module has been generated.
    stage = Path(tempfile.mkdtemp(prefix=".sync-", dir=outdir))
    try:
        specs = make_modules(
            dfns=dfns,
            outdir=outdir,
            stage=stage,
            skip=_SKIP,
            makedirs=all_packages,
            existing_only=not all_packages,
            verbose=verbose,
        )
        generated = {spec.outpath.relative_to(outdir).as_posix() for spec in specs}
        for rel in generated:
            try:
                compile((stage / rel).read_text(), rel, "exec")
            except SyntaxError as e:
                raise SyncError(f"Generated invalid Python for {rel}: {e}") from e

        on_disk = _generated_files(outdir)
        listed = _contract_files(outdir)
        if listed is None:
            kept = on_disk - generated
            removed: set[str] = set()
        else:
            kept = (on_disk & listed) - generated
            removed = on_disk - listed - generated
        if kept:
            warnings.warn(
                f"{len(kept)} generated module(s) have no DFN in '{source}' and were "
                f"left from the previous sync: {', '.join(sorted(kept))}",
                stacklevel=2,
            )

        (stage / _CONTRACT).write_text(_contract_text(version, generated | kept))
        _swap(stage, outdir, replace=[*sorted(generated), _CONTRACT], remove=sorted(removed))
    finally:
        shutil.rmtree(stage, ignore_errors=True)

    return SyncResult(
        version=version,
        source=str(source),
        outdir=outdir,
        files=tuple(spec.outpath for spec in specs),
        kept=tuple(outdir / f for f in sorted(kept)),
        removed=tuple(outdir / f for f in sorted(removed)),
    )
